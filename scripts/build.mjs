import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const config = JSON.parse(await readFile(join(root, "profile.config.json"), "utf8"));

const clean = (value = "") => String(value).replaceAll("|", "\\|").trim();
const xml = (value = "") =>
  String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&apos;");
const displayLink = (url = "") => (url ? `[访问](${url})` : "即将上线");

await mkdir(join(root, "assets"), { recursive: true });

await writeFile(
  join(root, "profile-data.js"),
  `// Generated by npm run build. Edit profile.config.json instead.\nwindow.PROFILE_DATA = ${JSON.stringify(config, null, 2)};\n`,
);

const bannerName = config.name.length > 18 ? `${config.name.slice(0, 17)}...` : config.name;
const banner = `<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="400" viewBox="0 0 1200 400" role="img" aria-labelledby="title desc">
  <title id="title">${xml(config.name)} / ${xml(config.title)}</title>
  <desc id="desc">${xml(config.name)} 的 AI 原生个人档案横幅。</desc>
  <rect width="1200" height="400" fill="#0b0d0c"/>
  <g opacity=".22" stroke="#d9ddd5" stroke-width="1">
    <path d="M0 80h1200M0 160h1200M0 240h1200M0 320h1200"/>
    <path d="M80 0v400M160 0v400M240 0v400M320 0v400M400 0v400M480 0v400M560 0v400M640 0v400M720 0v400M800 0v400M880 0v400M960 0v400M1040 0v400M1120 0v400"/>
  </g>
  <g fill="none" stroke="#a8c0ac">
    <path d="M750 80 910 45l115 102-44 158-163 38-107-127Z" opacity=".22"/>
    <path d="m910 45 88-29 80 74-53 57-115-102ZM1025 147l77 51-54 107h-67l44-158ZM818 343l103-38 73 27-46 68H790Z" opacity=".16"/>
    <path d="M750 80 818 343M1025 147 818 343M910 45l115 102M998 16l27 131M1102 198l-173 145M910 45 750 80" opacity=".12"/>
  </g>
  <g fill="#d7ff4f">
    <circle cx="750" cy="80" r="5"/>
    <circle cx="1025" cy="147" r="5"/>
    <circle cx="818" cy="343" r="5"/>
  </g>
  <g fill="#64d9e8">
    <circle cx="910" cy="45" r="4"/>
    <circle cx="1102" cy="198" r="4"/>
  </g>
  <g font-family="'Helvetica Neue', Arial, sans-serif" fill="#f2f0e9">
    <text x="64" y="62" font-size="14" letter-spacing="4" fill="#8d968c">AI-NATIVE PROFILE / ${new Date().getFullYear()}</text>
    <text x="64" y="190" font-size="92" font-weight="600">${xml(bannerName)}</text>
    <text x="64" y="244" font-size="28" fill="#b3bab2">${xml(config.title)}</text>
    <text x="64" y="334" font-size="16" fill="#7f887e">${xml(config.currentFocus)} / OPEN EXPERIMENTS</text>
  </g>
  <g transform="translate(1080 304)">
    <circle r="34" fill="#171b17" stroke="#687067"/>
    <text y="5" text-anchor="middle" font-family="monospace" font-size="12" fill="#f2f0e9">${xml(config.monogram)}</text>
  </g>
</svg>
`;

await writeFile(join(root, "assets/banner.svg"), banner);

const focusRows = config.focus
  .map(
    (item) =>
      `| **${clean(item.title)}** | ${clean(item.description)} | ${item.keywords.map(clean).join(" · ")} |`,
  )
  .join("\n");

const projectRows = config.projects
  .map(
    (item) =>
      `| ${clean(item.index)} | **${clean(item.title)}** | ${clean(item.summary)} | ${item.tags.map(clean).join(" · ")} | ${displayLink(item.url)} |`,
  )
  .join("\n");

const timelineRows = config.timeline
  .map((item) => `| **${clean(item.year)}** | ${clean(item.title)} | ${clean(item.description)} |`)
  .join("\n");

const social = [
  config.links.github && `[GitHub](${config.links.github})`,
  config.links.linkedin && `[LinkedIn](${config.links.linkedin})`,
  config.links.x && `[X](${config.links.x})`,
  config.links.email && `[Email](mailto:${config.links.email})`,
]
  .filter(Boolean)
  .join(" · ");

const readme = `<div align="center">
  <img src="./assets/banner.svg" alt="${clean(config.name)} / ${clean(config.title)}" width="100%" />
</div>

# ${config.name}

> ${config.tagline}

${config.intro}

**当前聚焦：** ${config.currentFocus}  
**所在地：** ${config.location}  
**状态：** <strong>${config.availability}</strong>

${social}

---

## 方向 / Focus

| 领域 | 我在做什么 | 关键词 |
| --- | --- | --- |
${focusRows}

## 代表项目 / Selected Work

| # | 项目 | 简介 | 标签 | 链接 |
| --- | --- | --- | --- | --- |
${projectRows}

## 工具 / Toolkit

${config.stack.map((item) => `\`${clean(item)}\``).join(" ")}

## 轨迹 / Journey

| 时间 | 主题 | 说明 |
| --- | --- | --- |
${timelineRows}

## 个人主页 / Profile Site

这个仓库同时包含一个可直接部署到 GitHub Pages 的 AI 原生个人档案：

- 动态关系图主视觉
- 本地运行的档案问答，不上传个人信息
- 桌面与移动端响应式布局
- 修改 \`profile.config.json\` 后运行 \`npm run build\` 即可同步 README 与网页内容

---

<div align="center">
  <sub>BUILT WITH CURIOSITY / ${new Date().getFullYear()}</sub>
</div>
`;

await writeFile(join(root, "README.md"), readme);
console.log("Built profile-data.js, README.md, and assets/banner.svg from profile.config.json");
